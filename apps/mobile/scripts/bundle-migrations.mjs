// Bundles drizzle-kit's SQL migrations (src/db/migrations/*.sql + meta/_journal.json) into a
// single TypeScript module, because Metro cannot import `.sql` files as strings.
// Re-run via `pnpm db:generate` after changing src/db/schema.ts.
import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const migrationsDir = join(process.cwd(), 'src', 'db', 'migrations');

const journal = JSON.parse(readFileSync(join(migrationsDir, 'meta', '_journal.json'), 'utf8'));
const entries = journal.entries.map(({ idx, when, tag, breakpoints }) => ({
  idx,
  when,
  tag,
  breakpoints,
}));

// `drizzle-orm/expo-sqlite/migrator` looks migrations up as `m<idx padded to 4>` (e.g. `m0000`),
// not by tag — any other key fails with "Missing migration" at startup.
const sql = {};
for (const entry of entries) {
  const key = `m${String(entry.idx).padStart(4, '0')}`;
  sql[key] = readFileSync(join(migrationsDir, `${entry.tag}.sql`), 'utf8');
}

const body = [
  '// Generated by scripts/bundle-migrations.mjs — do not edit by hand.',
  '// Re-run `pnpm db:generate` after changing src/db/schema.ts.',
  '',
  'const migrations = {',
  `  journal: { entries: ${JSON.stringify(entries)} },`,
  '  migrations: {',
  ...Object.entries(sql).map(([name, content]) => `    '${name}': ${JSON.stringify(content)},`),
  '  },',
  '};',
  '',
  'export default migrations;',
].join('\n');

writeFileSync(join(migrationsDir, 'index.ts'), `${body}\n`);
// drizzle-kit also emits migrations.js (imports .sql, which Metro can't bundle) — drop it.
rmSync(join(migrationsDir, 'migrations.js'), { force: true });

console.log('✓ Bundled migrations → src/db/migrations/index.ts');
